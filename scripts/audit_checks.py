"""Completeness and representativeness checks on the cleaned data.

Usage: python scripts/audit_checks.py data/clean reports/audit_report.md

Counts use every cleaned row. Anything that looks at asking_price_ratio values uses
training rows only, so the reserved test set stays unseen until D6.
"""
import os
import sys

import pandas as pd

clean_dir, report_path = sys.argv[1], sys.argv[2]
df = pd.read_csv(os.path.join(clean_dir, "southpark_listings_clean.csv"))
log = pd.read_csv(os.path.join(clean_dir, "cleaning_log.csv"))
train = df[df.split == "train"]
tt = train[train.has_target]

# Luxury stores on SouthPark's directory page, as Rebag spells the brand (None = not a resale brand)
SOUTHPARK_STORES = {"Balenciaga": "Balenciaga", "BOSS": "BOSS", "Breitling": "Breitling", "Burberry": "Burberry",
                    "CHANEL Fragrance and Beauty Boutique": None, "David Yurman": "David Yurman",
                    "Dolce & Gabbana": "Dolce & Gabbana", "Golden Goose": "Golden Goose", "Gucci": "Gucci",
                    "Louis Vuitton": "Louis Vuitton", "Neiman Marcus": None, "Nordstrom": None, "Omega": "Omega",
                    "Rolex Boutique": "Rolex", "Saint Laurent Paris": "Saint Laurent", "St. John": "St. John",
                    "TAG Heuer": "TAG Heuer", "Tiffany & Co.": "Tiffany & Co.", "TUDOR": "Tudor"}

def pct(x):
    return f"{100 * x:.1f}%"

def md(frame):
    return frame.to_markdown(index=False)

lines = ["# D2 Data Audit: Completeness and Representativeness",
         "",
         "Generated by `scripts/audit_checks.py` from `data/clean/`. Counts use all "
         f"{len(df):,} cleaned rows; figures that use `asking_price_ratio` values use the "
         f"{len(train):,} training rows only ({len(tt):,} with a target), so the reserved test set stays unseen.",
         "",
         "The target is Rebag's **advertised asking price** divided by its **estimated retail price**. "
         "These are listing prices, not completed sales.",
         "",
         "## Cleaning steps",
         "",
         md(log),
         ""]

# ---------- Completeness ----------
lines += ["## 1. Completeness", "", "### 1a. Missing values by column", ""]
miss = (df.isna().mean().rename("missing").reset_index().rename(columns={"index": "column"})
          .query("missing > 0").sort_values("missing", ascending=False))
miss["missing"] = miss.missing.map(pct)
lines += [md(miss), "",
          "`accessories` has no blanks because unknowns were filled with \"Unknown\"; "
          f"{pct((~df.accessories_known).mean())} of rows are unknown. "
          "`has_dust_bag`, `has_strap` and `has_authenticity_card` are blank for those rows on purpose.", ""]

lines += ["### 1b. Where the target exists", "",
          f"Only {df.has_target.sum():,} of {len(df):,} rows ({pct(df.has_target.mean())}) have an estimated retail "
          "price, so only they have a target. Coverage by group:", ""]
for col, label in [("brand", "Brand"), ("item_type", "Item type"), ("dropship_partner", "Partner (dropship) listing"),
                   ("recent", "Posted Sep–Oct 2026"), ("condition", "Condition")]:
    g = (df.groupby(col).agg(rows=("listing_id", "size"), with_target=("has_target", "sum"))
           .assign(coverage=lambda x: (x.with_target / x.rows).map(pct)).reset_index()
           .rename(columns={col: label}).sort_values("rows", ascending=False))
    lines += [md(g), ""]

lines += ["### 1c. Do listings with a target differ from those without? (training rows)", ""]
comp = []
for has, grp in train.groupby("has_target"):
    comp.append({"group": "with target" if has else "without target", "rows": len(grp),
                 "median asking price": f"${grp.asking_price.median():,.0f}",
                 "handbags": pct((grp.item_type == "Handbag").mean()),
                 "jewelry": pct((grp.item_type == "Jewelry").mean()),
                 "partner listings": pct(grp.dropship_partner.mean()),
                 "Louis Vuitton/Gucci/Chanel": pct(grp.brand.isin(["Louis Vuitton", "Gucci", "Chanel"]).mean()),
                 "condition Great or better": pct((grp.condition_rank >= 4).mean())})
lines += [md(pd.DataFrame(comp)), ""]

lines += ["### 1d. Where age is known", ""]
age = (df.groupby("brand").agg(rows=("listing_id", "size"), with_age=("item_age_years", "count"),
                               with_age_and_target=("item_age_years", lambda s: int((s.notna() & df.loc[s.index, "has_target"]).sum())))
         .query("with_age > 0").reset_index())
lb = df.year_is_lower_bound.sum()
lines += [md(age), "",
          f"{lb:,} of these years come from microchipped items (2021 or later), so their age is a maximum of 5 years, not an exact value.", ""]

# ---------- Representativeness ----------
lines += ["## 2. Representativeness", "", "### 2a. Which SouthPark luxury stores are covered", ""]
counts = df.brand.value_counts()
cover = pd.DataFrame([{"SouthPark store": s, "Rebag brand": b or "—",
                       "listings": int(counts.get(b, 0)) if b else 0,
                       "status": "not a resale brand (department store or beauty)" if b is None
                       else ("covered" if counts.get(b, 0) >= 30 else ("too few to analyze" if counts.get(b, 0) else "not on Rebag"))}
                      for s, b in SOUTHPARK_STORES.items()]).sort_values("listings", ascending=False)
lines += [md(cover), ""]

lines += ["### 2b. Concentration", ""]
share = (df.brand.value_counts(normalize=True).rename("share of rows").reset_index()
           .merge(tt.brand.value_counts(normalize=True).rename("share of training target rows").reset_index(), how="left"))
for c in share.columns[1:]:
    share[c] = share[c].fillna(0).map(pct)
lines += [md(share), ""]
item = (df.item_type.value_counts(normalize=True).rename("share of rows").reset_index()
          .merge(tt.item_type.value_counts(normalize=True).rename("share of training target rows").reset_index(), how="left"))
for c in item.columns[1:]:
    item[c] = item[c].fillna(0).map(pct)
lines += [md(item), ""]

lines += ["### 2c. Groups too small for reliable estimates (training target rows)", ""]
cells = tt.groupby(["brand", "item_type"]).size().rename("training target rows").reset_index()
small = cells[cells["training target rows"] < 30].sort_values("training target rows", ascending=False)
lines += [f"{len(small)} of {len(cells)} brand × item type groups have fewer than 30 rows with a target:", "", md(small), ""]

lines += ["### 2d. Time on market (training rows)", ""]
tm = (tt.assign(posted=tt.recent.map({True: "Sep–Oct 2026", False: "Before Sep 2026"}))
        .groupby("posted").agg(rows=("listing_id", "size"), median_ratio=("asking_price_ratio", "median"),
                                median_days_listed=("days_listed", "median")).reset_index())
lines += [md(tm.round(1)), "",
          "Listings that have been on the market longer have lower ratios, which is consistent with markdowns. "
          "D3 will compare results on all listings vs recent listings only.", ""]

lines += ["### 2e. The target has a ceiling (training rows)", ""]
q = tt.asking_price_ratio.quantile([0, 0.05, 0.25, 0.5, 0.75, 0.95, 1]).round(1)
lines += [md(pd.DataFrame({"percentile": ["min", "5th", "25th", "median", "75th", "95th", "max"], "asking_price_ratio": q.values})), "",
          "No listing is priced above 83.3% of estimated retail, even for items known to sell above retail. "
          "Rebag's retail estimate or pricing appears to cap the ratio, so the target cannot show appreciation.", ""]

lines += ["## 3. Summary of concerns", "",
          f"- **Small target set:** {pct(df.has_target.mean())} of rows have a target; coverage is uneven across brands (see 1b).",
          f"- **Retail price comes only from partner listings:** all {df.has_target.sum():,} rows with a target are "
          "partner (dropship) listings; Rebag's own listings never show a retail price. Results describe partner listings.",
          "- **Selection:** rows with a target are more often handbags and less often Pristine or jewelry (see 1b and 1c), "
          "so they are not a random subset of all listings.",
          "- **Age only for two brands:** Louis Vuitton and Chanel; microchipped items give only a maximum age.",
          "- **Concentration:** Louis Vuitton, Gucci and Chanel dominate; watches and several SouthPark stores are absent or too small.",
          "- **One reseller, one day:** all rows are Rebag listings on October 20, 2026; partner (dropship) listings are about half the data.",
          "- **Asking prices, not sales:** older listings likely include markdowns, and the ratio is capped at 83.3%.",
          ""]

os.makedirs(os.path.dirname(report_path), exist_ok=True)
open(report_path, "w", encoding="utf-8").write("\n".join(lines))
print("\n".join(lines))
